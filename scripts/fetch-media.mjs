/**
 * Fetch, crop and encode the site photography.
 *
 * Reads scripts/media-manifest.json — one entry per figure, naming a freely
 * licensed source image, the aspect ratio that figure is rendered at, and the
 * focal point that must survive the crop. Writes optimised WebP into
 * /public/media, plus a tiny inline blur placeholder for each so the dark page
 * never flashes an empty box while a photograph loads.
 *
 * Originals are cached under /.media-cache so re-running only re-encodes.
 * Pass --force to re-download them.
 *
 *   node scripts/fetch-media.mjs [--force] [--only=id,id]
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "media");
const CACHE_DIR = path.join(ROOT, ".media-cache");
const MANIFEST = path.join(ROOT, "scripts", "media-manifest.json");
const RESULT = path.join(ROOT, "scripts", "media-generated.json");

const args = process.argv.slice(2);
const FORCE = args.includes("--force");
const ONLY = args
  .find((a) => a.startsWith("--only="))
  ?.slice("--only=".length)
  .split(",")
  .filter(Boolean);

/** Long-edge cap per role. Heroes are seen full-bleed; thumbnails never are. */
const WIDTH_FOR = { hero: 2400, feature: 2000, gallery: 1500, portrait: 1000 };

/**
 * Wikimedia's robot policy answers 429 to any User-Agent without contact
 * details in it, so this string is load-bearing, not decoration.
 * https://foundation.wikimedia.org/wiki/Policy:Wikimedia_Foundation_User-Agent_Policy
 */
const UA = "papaha.travel-media-fetch/1.0 (https://papaha.travel; site asset preparation)";

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function download(url, dest) {
  let last = "";
  for (let attempt = 0; attempt < 5; attempt += 1) {
    if (attempt) await sleep(4000 * 2 ** (attempt - 1));
    try {
      const res = await fetch(url, {
        headers: { "User-Agent": UA, Accept: "image/*,*/*" },
        redirect: "follow",
        signal: AbortSignal.timeout(120000),
      });
      if (!res.ok) {
        last = `HTTP ${res.status}`;
        continue;
      }
      const buf = Buffer.from(await res.arrayBuffer());
      // Commons hands back an HTML error page with a 200 often enough to matter.
      if (buf.length < 8000) {
        last = `suspiciously small (${buf.length} B)`;
        continue;
      }
      await fs.writeFile(dest, buf);
      return buf;
    } catch (err) {
      last = err.message ?? String(err);
    }
  }
  throw new Error(last || "download failed");
}

/**
 * Crop to the exact ratio the layout asks for, keeping `focus` in frame.
 *
 * Doing this at build-prep time rather than leaning on object-cover means the
 * bytes we ship are all bytes the visitor can actually see, and the composition
 * is decided once — by someone who looked at the photograph — instead of by
 * whatever the viewport happens to be.
 */
function cropRect(width, height, ratio, focus) {
  const fx = (focus?.x ?? 50) / 100;
  const fy = (focus?.y ?? 50) / 100;
  const clamp = (v, max) => Math.max(0, Math.min(Math.round(v), Math.round(max)));

  if (width / height > ratio) {
    const w = Math.round(height * ratio);
    return { left: clamp(fx * width - w / 2, width - w), top: 0, width: w, height };
  }
  const h = Math.round(width / ratio);
  return { left: 0, top: clamp(fy * height - h / 2, height - h), width, height: h };
}

async function blurDataUrl(pipeline) {
  const buf = await pipeline
    .clone()
    .resize(20, null, { fit: "inside" })
    .webp({ quality: 40, alphaQuality: 0, effort: 6 })
    .toBuffer();
  return `data:image/webp;base64,${buf.toString("base64")}`;
}

/**
 * Emit the id -> photograph lookup that `Figure` resolves against.
 *
 * The alternative was writing `src` and `blur` into all fifty-odd figure
 * literals across src/content, which would mean a large mechanical diff every
 * time a single photograph changed, and blur data URLs inlined in files people
 * actually read. A generated lookup keyed by figure id keeps the content files
 * about content, and makes swapping the photography a one-command operation.
 */
async function writeMediaModule(generated) {
  const rows = Object.entries(generated)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([id, g]) =>
        `  "${id}": {\n    src: "${g.src}",\n    width: ${g.width},\n    height: ${g.height},\n    blur:\n      "${g.blur}",\n  },`,
    )
    .join("\n");

  const file = `// GENERATED BY scripts/fetch-media.mjs. Do not edit by hand.
//
// The photograph that fills each figure slot, keyed by figure id. \`Figure\`
// reads this: a figure with no entry here falls back to its drawn survey plate,
// and an explicit \`src\` on the figure itself still wins over anything here.
//
// Provenance and licensing live in scripts/media-manifest.json; the visible
// credits are generated into src/content/credits.ts and rendered at /credits.

export type MediaEntry = {
  src: string;
  width: number;
  height: number;
  /** Twenty-pixel WebP data URL, held behind the photograph while it loads. */
  blur: string;
};

export const MEDIA: Record<string, MediaEntry> = {
${rows}
};
`;

  await fs.writeFile(path.join(ROOT, "src", "content", "media.ts"), file);
  console.log(`  ✎ src/content/media.ts (${Object.keys(generated).length} photographs)`);
}

/** Map a licence short name onto its deed, so the credit line can link out. */
const LICENCE_URL = {
  "CC BY-SA 4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
  "CC BY-SA 3.0": "https://creativecommons.org/licenses/by-sa/3.0/",
  "CC BY-SA 2.0": "https://creativecommons.org/licenses/by-sa/2.0/",
  "CC BY 4.0": "https://creativecommons.org/licenses/by/4.0/",
  "CC BY 3.0": "https://creativecommons.org/licenses/by/3.0/",
  "CC BY 2.0": "https://creativecommons.org/licenses/by/2.0/",
  CC0: "https://creativecommons.org/publicdomain/zero/1.0/",
  "Public domain": "https://en.wikipedia.org/wiki/Public_domain",
};

/**
 * Emit the attribution list.
 *
 * Every photograph on this site is somebody else's work, used under a licence
 * that requires credit. That is not a footnote we can decide to skip: without
 * this file the site is simply in breach. Generated, so it can never drift out
 * of step with what /public/media actually contains.
 */
async function writeCredits(manifest, generated) {
  // Own photography needs no attribution, so it stays off the credits page.
  const credited = manifest.figures.filter(
    (item) => generated[item.id] && !item.source.file,
  );
  const rows = credited
    .map((item) => {
      const s = item.source;
      const esc = (v) => String(v ?? "").replace(/\\/g, "\\\\").replace(/"/g, '\\"');
      return `  {
    id: "${esc(item.id)}",
    title: "${esc(s.title)}",
    author: "${esc(s.author)}",
    license: "${esc(s.license)}",
    licenseUrl: "${esc(LICENCE_URL[s.license] ?? "https://creativecommons.org/licenses/")}",
    sourceUrl: "${esc(s.page)}",
  },`;
    })
    .join("\n");

  const file = `// GENERATED BY scripts/fetch-media.mjs. Do not edit by hand.
//
// Photograph credits. The images on this site come from Wikimedia Commons under
// CC BY, CC BY-SA, CC0 and public domain terms, all of which require or invite
// attribution. /credits renders this list, and the footer links to it.
//
// To change a photograph, edit scripts/media-manifest.json and re-run
// \`node scripts/fetch-media.mjs\`.

export type PhotoCredit = {
  /** The figure id it fills, matching the ids in src/content. */
  id: string;
  title: string;
  author: string;
  license: string;
  licenseUrl: string;
  sourceUrl: string;
};

export const PHOTO_CREDITS: PhotoCredit[] = [
${rows}
];
`;

  await fs.writeFile(path.join(ROOT, "src", "content", "credits.ts"), file);
  console.log(`  ✎ src/content/credits.ts (${credited.length} credits)`);
}

async function main() {
  const manifest = JSON.parse(await fs.readFile(MANIFEST, "utf8"));
  await fs.mkdir(OUT_DIR, { recursive: true });
  await fs.mkdir(CACHE_DIR, { recursive: true });

  const generated = {};
  const failures = [];
  let downloaded = 0;

  for (const item of manifest.figures) {
    if (ONLY && !ONLY.includes(item.id)) continue;

    const outPath = path.join(OUT_DIR, `${item.id}.webp`);
    const cachePath = path.join(CACHE_DIR, `${item.id}.src`);

    try {
      let source;
      if (item.source.file) {
        // The company's own photography, committed under /media-src. Nothing to
        // download and nothing to credit: it is already theirs.
        source = await fs.readFile(path.join(ROOT, item.source.file));
        process.stdout.write(`  ⌂ ${item.id} … `);
        process.stdout.write(`${(source.length / 1024 / 1024).toFixed(1)} MB\n`);
      } else {
      try {
        if (FORCE) throw new Error("forced refetch");
        source = await fs.readFile(cachePath);
        if (source.length < 8000) throw new Error("bad cache");
      } catch {
        process.stdout.write(`  ↓ ${item.id} … `);
        // One at a time with a gap. We are a guest on someone else's servers.
        if (downloaded) await sleep(1500);
        source = await download(item.source.url, cachePath);
        downloaded += 1;
        process.stdout.write(`${(source.length / 1024 / 1024).toFixed(1)} MB\n`);
      }
      }

      const meta = await sharp(source).metadata();
      // metadata() reports the stored dimensions, but .rotate() applies the EXIF
      // orientation first, so for a quarter-turned photo the crop rectangle has
      // to be computed against the swapped pair or .extract() falls off the edge.
      const turned = (meta.orientation ?? 1) >= 5;
      const srcW = turned ? meta.height : meta.width;
      const srcH = turned ? meta.width : meta.height;
      const rect = cropRect(srcW, srcH, item.ratio, item.focus);
      const cap = WIDTH_FOR[item.role] ?? WIDTH_FOR.gallery;
      const targetW = Math.min(cap, rect.width);

      const pipeline = sharp(source)
        .rotate() // honour EXIF orientation before we measure anything
        .extract(rect)
        .resize(targetW, null, { fit: "inside", kernel: "lanczos3", withoutEnlargement: true });

      const info = await pipeline
        .clone()
        .webp({ quality: item.role === "hero" ? 84 : 80, effort: 6, smartSubsample: true })
        .toFile(outPath);

      generated[item.id] = {
        src: `/media/${item.id}.webp`,
        width: info.width,
        height: info.height,
        bytes: info.size,
        blur: await blurDataUrl(pipeline),
        credit: item.source,
      };

      console.log(
        `  ✓ ${item.id.padEnd(17)} ${info.width}×${info.height}  ${(info.size / 1024).toFixed(0)} KB`,
      );
    } catch (err) {
      failures.push({ id: item.id, error: String(err.message ?? err) });
      console.log(`  ✗ ${item.id.padEnd(17)} ${err.message ?? err}`);
    }
  }

  if (!ONLY) {
    // Drop anything /public/media still holds that the manifest no longer
    // names, so removing a photograph from the manifest actually removes it
    // from the site rather than leaving an orphan the lookup no longer points at.
    const wanted = new Set(manifest.figures.map((f) => `${f.id}.webp`));
    for (const name of await fs.readdir(OUT_DIR)) {
      if (name.endsWith(".webp") && !wanted.has(name)) {
        await fs.unlink(path.join(OUT_DIR, name));
        console.log(`  ✕ ${name} (no longer in the manifest)`);
      }
    }
  }

  if (ONLY) {
    // A partial run knows nothing about the slots it skipped, so writing the
    // derived files here would silently drop every other photograph.
    console.log("\n--only run: skipped writing src/content/media.ts and credits.ts");
  } else {
    await fs.writeFile(RESULT, JSON.stringify(generated, null, 2) + "\n");
    await writeMediaModule(generated);
    await writeCredits(manifest, generated);
  }

  const totalBytes = Object.values(generated).reduce((n, g) => n + g.bytes, 0);
  console.log(
    `\n${Object.keys(generated).length} images, ${(totalBytes / 1024 / 1024).toFixed(1)} MB total`,
  );
  if (failures.length) {
    console.log(`\n${failures.length} failed:`);
    for (const f of failures) console.log(`  ${f.id}: ${f.error}`);
    process.exitCode = 1;
  }
}

main();
